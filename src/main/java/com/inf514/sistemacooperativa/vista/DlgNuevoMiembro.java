    private void pnlGuardarBotonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_pnlGuardarBotonMouseClicked
       try {
            // 1. Recopilar datos (Evitando capturar los textos de placeholder)
            String nombre = txtNombre.getText().trim();
            if (nombre.equals("ingrese su nombre completo")) nombre = "";
            
            String cedula = txtCedula.getText().trim();
            if (cedula.equals("digite su cedula sin guiones")) cedula = "";
            
            String telefono = txtTelefono.getText().trim();
            if (telefono.equals("Telefono")) telefono = "";
            
            String correo = txtCorreo.getText().trim();
            if (correo.equals("Correo Electronico")) correo = "";
            
            String direccion = txtDireccion.getText().trim();
            if (direccion.equals("dirección")) direccion = "";
            
            String ocupacion = txtOcupacion.getText().trim();
            if (ocupacion.equals("Ocupacion")) ocupacion = "";

            String beneficiario = txtBeneficiario.getText().trim();
            if (beneficiario.equals("Nombre del beneficiario") || beneficiario.isEmpty()) {
                beneficiario = "Sin asignar"; // Valor por defecto si lo dejan vacío
            }
            // 2. Validaciones básicas
            if (nombre.isEmpty() || cedula.isEmpty()) {
                JOptionPane.showMessageDialog(this, "El nombre y la cédula son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                return; 
            }

            // 3. Conversiones
            double ingreso = 0.0;
            String textoIngreso = txtIngresosMensuales.getText().trim();
            if (!textoIngreso.isEmpty() && !textoIngreso.equals("Ingresos Mensuales")) { 
                ingreso = Double.parseDouble(textoIngreso);
            }

            DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            String textoFecha = txtFechaNacimiento.getText().trim();
            // Como usaste un MaskFormatter, la fecha viene con formato estricto
            LocalDate fechaNac = LocalDate.parse(textoFecha, formatter);

            // 4. Instanciar y Guardar (Ahora usa la variable beneficiario real)
            Miembro nuevoMiembro = new Miembro(cedula, nombre, telefono, correo, direccion, fechaNac, ocupacion, ingreso, beneficiario, true);
            MiembroDAO dao = new MiembroDAO();
            dao.guardar(nuevoMiembro);

            // 5. Cierre exitoso
            JOptionPane.showMessageDialog(this, "Socio registrado exitosamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();

        } catch (java.time.format.DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Ingrese una fecha real.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "El ingreso mensual debe ser un número válido (ej. 25000.50).", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos: " + ex.getMessage(), "Error Crítico", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_pnlGuardarBotonMouseClicked

