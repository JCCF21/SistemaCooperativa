    private void restaurarPlaceholders(String campoActivo) {
        if (!campoActivo.equals("nombre") && txtNombre.getText().trim().isEmpty()) {
            txtNombre.setText("ingrese su nombre completo");
            txtNombre.setForeground(Color.GRAY);
        }
        if (!campoActivo.equals("cedula") && txtCedula.getText().trim().isEmpty()) {
            txtCedula.setText("digite su cedula sin guiones");
            txtCedula.setForeground(Color.GRAY);
        }
        if (!campoActivo.equals("telefono") && txtTelefono.getText().trim().isEmpty()) {
            txtTelefono.setText("Telefono");
            txtTelefono.setForeground(Color.GRAY);
        }
        if (!campoActivo.equals("correo") && txtCorreo.getText().trim().isEmpty()) {
            txtCorreo.setText("Correo Electronico");
            txtCorreo.setForeground(Color.GRAY);
        }
        if (!campoActivo.equals("direccion") && txtDireccion.getText().trim().isEmpty()) {
            txtDireccion.setText("dirección");
            txtDireccion.setForeground(Color.GRAY);
        }
        if (!campoActivo.equals("ocupacion") && txtOcupacion.getText().trim().isEmpty()) {
            txtOcupacion.setText("Ocupacion");
            txtOcupacion.setForeground(Color.GRAY);
        }
        if (!campoActivo.equals("ingresos") && txtIngresosMensuales.getText().trim().isEmpty()) {
            txtIngresosMensuales.setText("Ingresos Mensuales");
            txtIngresosMensuales.setForeground(Color.GRAY);
        }
        if (!campoActivo.equals("beneficiario") && txtBeneficiario.getText().trim().isEmpty()) {
            txtBeneficiario.setText("Beneficiario");
            txtBeneficiario.setForeground(Color.GRAY);
        }
    }
