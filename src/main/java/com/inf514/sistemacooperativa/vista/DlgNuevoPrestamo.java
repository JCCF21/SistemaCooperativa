    private void calcularPrestamo() {

    txtInteresTotal.setText("");
    txtTotalPagar.setText("");
    txtCuotaMensual.setText("");

    if (txtMonto.getText().trim().isEmpty()
            || txtTasaInteres.getText().isEmpty()) {
        return;
    }

    try {
        double monto = Double.parseDouble(
                txtMonto.getText().trim());

        int cuotas = Integer.parseInt(
                cmbCuotas.getSelectedItem().toString());

        double tasaAnual = Double.parseDouble(
                txtTasaInteres.getText().replace("%", ""));

        if (!Double.isFinite(monto) || monto <= 0) {
            return;
        }

        double tasaMensual = tasaAnual / 100 / 12;

        // Sistema de amortización francés
        double cuotaMensual = monto * tasaMensual
                / (1 - Math.pow(1 + tasaMensual, -cuotas));

        double totalPagar = cuotaMensual * cuotas;
        double interesTotal = totalPagar - monto;

        txtCuotaMensual.setText(
                String.format("%.2f", cuotaMensual));

        txtTotalPagar.setText(
                String.format("%.2f", totalPagar));

        txtInteresTotal.setText(
                String.format("%.2f", interesTotal));

    } catch (NumberFormatException e) {
        // Esperar hasta que se introduzcan valores válidos.
    }
}

