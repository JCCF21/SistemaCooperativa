    private void btnBuscarMiembroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarMiembroActionPerformed
        // TODO add your handling code here:

        miembroSeleccionado = null;
        txtNombreMiembro.setText("");
        String cedulaBuscada = txtCedula.getText().trim();

        if (cedulaBuscada.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Introduce la cédula del miembro.");
            return;
        }

        try {

            MiembroDAO dao = new MiembroDAO();

            List<Miembro> resultados = dao.buscarPorCedula(cedulaBuscada);

            Miembro miembroEncontrado = null;

            // Comprobar que la cédula coincida exactamente
            for (Miembro miembro : resultados) {

                if (miembro.getCedula().trim().equalsIgnoreCase(cedulaBuscada)) {
                    miembroEncontrado = miembro;
                    break;
                }
            }

            if (miembroEncontrado != null) {
                miembroSeleccionado = miembroEncontrado;

                txtNombreMiembro.setText(miembroEncontrado.getNombreCompleto());

                JOptionPane.showMessageDialog(this,
                    "Miembro encontrado correctamente.");

            } else {

                txtNombreMiembro.setText("");

                JOptionPane.showMessageDialog(this,
                    "No se encontró ningún miembro con esa cédula.");
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                "Error al buscar el miembro: " + e.getMessage());
        }

    }//GEN-LAST:event_btnBuscarMiembroActionPerformed

    private void btnGuardarSolicitudActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarSolicitudActionPerformed
        
if (miembroSeleccionado == null
        || !miembroSeleccionado.getCedula().trim()
                .equalsIgnoreCase(txtCedula.getText().trim())) {

    JOptionPane.showMessageDialog(this,
            "Debes buscar y seleccionar un miembro.");
    return;
}

if (txtMonto.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Introduce el monto solicitado.");
    return;
}

if (cmbCuotas.getSelectedIndex() <= 0) {
    JOptionPane.showMessageDialog(this,
            "Selecciona la cantidad de cuotas.");
    return;
}

try {
    calcularPrestamo();

    BigDecimal monto = new BigDecimal(
            txtMonto.getText().trim());

    if (monto.signum() <= 0) {
        JOptionPane.showMessageDialog(this,
                "El monto debe ser mayor que cero.");
        return;
    }

    Prestamo prestamo = new Prestamo();

    prestamo.setMiembro(miembroSeleccionado);
    prestamo.setMontoSolicitado(monto);
    prestamo.setFechaSolicitud(LocalDate.now());

    prestamo.setCantidadCuotas(Integer.parseInt(
            cmbCuotas.getSelectedItem().toString()));

    prestamo.setTasaInteres(new BigDecimal(
            txtTasaInteres.getText().replace("%", "").trim()));

    prestamo.setInteresTotal(new BigDecimal(
            txtInteresTotal.getText().replace(",", ".")));

    prestamo.setTotalPagar(new BigDecimal(
            txtTotalPagar.getText().replace(",", ".")));

    prestamo.setCuotaMensual(new BigDecimal(
            txtCuotaMensual.getText().replace(",", ".")));

    prestamo.setEstado("En espera");

    PrestamoDAO dao = new PrestamoDAO();
    dao.guardar(prestamo);

    txtIdPrestamo.setText(
            String.valueOf(prestamo.getId()));

    JOptionPane.showMessageDialog(this,
            "Solicitud guardada correctamente."
            + "\nID del préstamo: " + prestamo.getId());

    dispose();

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,
            "Verifica los valores del préstamo.");

} catch (Exception e) {

    JOptionPane.showMessageDialog(this,
            "Error al guardar el préstamo: "
            + e.getMessage());
}


       
    }//GEN-LAST:event_btnGuardarSolicitudActionPerformed

    private void cmbCuotasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbCuotasActionPerformed
       

    String cuotas = cmbCuotas.getSelectedItem().toString();

    switch (cuotas) {
        case "6":
            txtTasaInteres.setText("10%");
            break;

        case "12":
            txtTasaInteres.setText("12%");
            break;

        case "24":
            txtTasaInteres.setText("14%");
            break;

        case "36":
            txtTasaInteres.setText("16%");
            break;

        default:
            txtTasaInteres.setText("");
            break;
    }
    
    calcularPrestamo();

    }//GEN-LAST:event_cmbCuotasActionPerformed

