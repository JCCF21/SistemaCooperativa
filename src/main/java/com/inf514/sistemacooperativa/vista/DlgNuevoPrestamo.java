    private void btnBuscarMiembroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarMiembroActionPerformed
        // TODO add your handling code here:

        miembroSeleccionado = null;
        txtNombreMiembro.setText("");
        String cedulaBuscada = txtCedula.getText().trim();

        if (cedulaBuscada.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Introduce la cédula del miembro.");
            return;
        }

        try {

            MiembroDAO dao = new MiembroDAO();

            List<Miembro> resultados = dao.buscarPorCedula(cedulaBuscada);

            Miembro miembroEncontrado = null;

            // Comprobar que la cédula coincida exactamente
            for (Miembro miembro : resultados) {

                if (miembro.getCedula().trim().equalsIgnoreCase(cedulaBuscada)) {
                    miembroEncontrado = miembro;
                    break;
                }
            }

            if (miembroEncontrado != null) {
                miembroSeleccionado = miembroEncontrado;

                txtNombreMiembro.setText(miembroEncontrado.getNombreCompleto());

                JOptionPane.showMessageDialog(this,
                    "Miembro encontrado correctamente.");

            } else {

                txtNombreMiembro.setText("");

                JOptionPane.showMessageDialog(this,
                    "No se encontró ningún miembro con esa cédula.");
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                "Error al buscar el miembro: " + e.getMessage());
        }

    }//GEN-LAST:event_btnBuscarMiembroActionPerformed

