    private void btnConfirmarPagoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarPagoActionPerformed
        if (prestamoSeleccionado == null
        || cmbCuotasPagar.getSelectedItem() == null) {

    JOptionPane.showMessageDialog(this,
            "No hay cuotas disponibles para pagar.");
    return;
}
//....
int cantidadCuotas = Integer.parseInt(
        cmbCuotasPagar.getSelectedItem().toString());

int respuesta = JOptionPane.showConfirmDialog(this,
        "¿Deseas registrar el pago de "
        + cantidadCuotas + " cuota(s)?"
        + "\nMonto: RD$ " + txtMontoPago.getText(),
        "Confirmar pago",
        JOptionPane.YES_NO_OPTION,
        JOptionPane.QUESTION_MESSAGE);

if (respuesta != JOptionPane.YES_OPTION) {
    return;
}

try {
    pagoPrestamoDAO.registrarPago(
            prestamoSeleccionado.getId(),
            cantidadCuotas);

    JOptionPane.showMessageDialog(this,
            "Pago registrado correctamente.");

    dispose();

} catch (Exception e) {

    JOptionPane.showMessageDialog(this,
            "Error al registrar el pago: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnConfirmarPagoActionPerformed

