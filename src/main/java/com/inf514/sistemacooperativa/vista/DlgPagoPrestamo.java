    public DlgPagoPrestamo(java.awt.Frame parent, boolean modal,
        Prestamo prestamo) {

    this(parent, modal);

    this.prestamoSeleccionado = prestamo;

    setTitle("Registrar pago de préstamo");
    setLocationRelativeTo(parent);
    setResizable(false);

    txtIdPrestamo.setText(String.valueOf(prestamo.getId()));

    txtFechaPago.setText(LocalDate.now().format(
            DateTimeFormatter.ofPattern("dd/MM/yyyy")));

    txtCedula.setText(prestamo.getMiembro().getCedula());

    txtNombreMiembro.setText(
            prestamo.getMiembro().getNombreCompleto());

    txtTotalPagar.setText(
            prestamo.getTotalPagar().toPlainString());

    txtCuotaMensual.setText(
            prestamo.getCuotaMensual().toPlainString());
    
    BigDecimal totalPagado = pagoPrestamoDAO.obtenerTotalPagado(
        prestamo.getId());

int cuotasPagadas = pagoPrestamoDAO.obtenerCuotasPagadas(
        prestamo.getId());

saldoPendiente = prestamo.getTotalPagar().subtract(totalPagado);

cuotasRestantes = prestamo.getCantidadCuotas() - cuotasPagadas;

txtTotalPagado.setText(totalPagado.toPlainString());

txtCuotasPagadas.setText(
        cuotasPagadas + " de " + prestamo.getCantidadCuotas());

txtSaldoPendiente.setText(saldoPendiente.toPlainString());

cmbCuotasPagar.removeAllItems();

for (int i = 1; i <= cuotasRestantes; i++) {
    cmbCuotasPagar.addItem(String.valueOf(i));
}

if (cuotasRestantes > 0) {
    cmbCuotasPagar.setSelectedIndex(0);
} else {
    cmbCuotasPagar.setEnabled(false);
    btnConfirmarPago.setEnabled(false);
}

calcularMontoPago();
}
    private void calcularMontoPago() {

    txtMontoPago.setText("");

    if (prestamoSeleccionado == null
            || cmbCuotasPagar.getSelectedItem() == null) {
        return;
    }

    int cantidadCuotas = Integer.parseInt(
            cmbCuotasPagar.getSelectedItem().toString());

    BigDecimal montoPago = prestamoSeleccionado
            .getCuotaMensual()
            .multiply(BigDecimal.valueOf(cantidadCuotas));

    if (cantidadCuotas == cuotasRestantes) {
        montoPago = saldoPendiente;
    }

    txtMontoPago.setText(montoPago.toPlainString());
}

