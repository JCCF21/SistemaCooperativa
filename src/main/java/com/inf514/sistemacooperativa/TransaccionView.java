    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
                                                    
   try {
            // 1. Leemos lo que el usuario escribió en la pantalla
            int idCuenta = Integer.parseInt(txtIdCuenta.getText());
            String tipo = cmbTipoTransaccion.getSelectedItem().toString();
            double monto = Double.parseDouble(txtMonto.getText());
            String descripcion = txtDescripcion.getText();
            
            // Asignamos un ID de administrador por defecto
            Integer idAdmin = 1; 

            // 2. Creamos el objeto usando tu clase Transacciones
            Transacciones nuevaTransaccion = new Transacciones();
            nuevaTransaccion.setIdCuenta(idCuenta);
            nuevaTransaccion.setTipo(tipo);
            nuevaTransaccion.setMonto(monto); // Valida automáticamente si es mayor a 0
            nuevaTransaccion.setDescripcion(descripcion);
            nuevaTransaccion.setIdAdmin(idAdmin);

            // 3. Mostramos un mensaje de éxito con los datos guardados
            javax.swing.JOptionPane.showMessageDialog(this, 
                "¡Transacción registrada con éxito!\n" + nuevaTransaccion.toString(), 
                "Información", 
                javax.swing.JOptionPane.INFORMATION_MESSAGE);

            // 4. Limpiamos los campos para una nueva transacción
            txtIdCuenta.setText("");
            txtMonto.setText("");
            txtDescripcion.setText("");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Error: Por favor, asegúrate de escribir números válidos en ID Cuenta y Monto.", 
                "Error de formato", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (IllegalArgumentException e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                e.getMessage(), 
                "Error de validación", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

